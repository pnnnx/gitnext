//! Markdown map generation: one `DIR.md` per directory under `.gitnext/map/`
//! (mirroring the tree) plus an agent guide block in the root `AGENTS.md`.
//!
//! Generated content lives between `gitnext:auto` markers; anything after the
//! end marker (the "Notes" section) is preserved across regenerations.

use anyhow::Result;
use gitnext_index::{dir_of, Graph, GITNEXT_DIR};
use gitnext_parse::{EdgeKind, Kind};
use std::collections::{BTreeMap, BTreeSet, HashMap, HashSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

pub const AUTO_START: &str = "<!-- gitnext:auto:start — generated by `gitnext map`, do not edit by hand -->";
pub const AUTO_END: &str = "<!-- gitnext:auto:end -->";
const NOTES_TAIL: &str = "\n## Notes\n\n<!-- Free-form notes for humans and agents. Everything below the auto:end marker is kept. -->\n";
const MAX_SIG: usize = 160;

#[derive(Debug, Default)]
pub struct MapOutput {
    pub written: Vec<PathBuf>,
    pub unchanged: usize,
    pub removed: Vec<PathBuf>,
    /// ≈ tokens to read all parsed source files.
    pub source_tokens: usize,
    /// ≈ tokens of all DIR.md files.
    pub map_tokens: usize,
}

/// Rough token estimate (≈ 4 characters per token for code/English).
pub fn est_tokens(s: &str) -> usize {
    s.len().div_ceil(4)
}

/// Path of the map file for a directory ("" = repo root).
pub fn map_path(root: &Path, dir: &str) -> PathBuf {
    let base = root.join(GITNEXT_DIR).join("map");
    if dir.is_empty() { base.join("DIR.md") } else { base.join(dir).join("DIR.md") }
}

/// Regenerate the whole map. Only touches files whose content changed.
pub fn write_map(root: &Path, g: &Graph) -> Result<MapOutput> {
    let mut out = MapOutput::default();
    let dirs = g.dirs();
    let ctx = Ctx::new(root, g);
    for dir in &dirs {
        let path = map_path(root, dir);
        let body = render_dir(&ctx, dir);
        out.map_tokens += est_tokens(&body);
        write_spliced(&path, &body, &mut out)?;
    }
    out.source_tokens = ctx.source_tokens();
    // Remove map files of directories that disappeared (unless they hold notes).
    let map_root = root.join(GITNEXT_DIR).join("map");
    let live: std::collections::HashSet<PathBuf> = dirs.iter().map(|d| map_path(root, d)).collect();
    for entry in walk_md(&map_root) {
        if !live.contains(&entry) {
            let txt = std::fs::read_to_string(&entry).unwrap_or_default();
            if notes_of(&txt).is_none_or(|n| n.trim() == NOTES_TAIL.trim()) {
                let _ = std::fs::remove_file(&entry);
                out.removed.push(entry);
            }
        }
    }
    let agents = root.join("AGENTS.md");
    write_spliced(&agents, &render_agents(&ctx), &mut out)?;
    Ok(out)
}

fn walk_md(dir: &Path) -> Vec<PathBuf> {
    let mut v = vec![];
    if let Ok(rd) = std::fs::read_dir(dir) {
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                v.extend(walk_md(&p));
            } else if p.file_name().is_some_and(|n| n == "DIR.md") {
                v.push(p);
            }
        }
    }
    v
}

fn notes_of(txt: &str) -> Option<&str> {
    txt.find(AUTO_END).map(|i| &txt[i + AUTO_END.len()..])
}

/// Replace the auto block in `path`, keeping whatever surrounds it.
fn write_spliced(path: &Path, auto: &str, out: &mut MapOutput) -> Result<()> {
    let block = format!("{AUTO_START}\n{}\n{AUTO_END}", auto.trim_end());
    let existing = std::fs::read_to_string(path).ok();
    let new = match &existing {
        Some(old) => match (old.find(AUTO_START.split(" —").next().unwrap()), old.find(AUTO_END)) {
            (Some(s), Some(e)) if e > s => format!("{}{}{}", &old[..s], block, &old[e + AUTO_END.len()..]),
            _ => format!("{}\n\n{}\n", old.trim_end(), block), // user file without markers: append
        },
        None if path.ends_with("AGENTS.md") => format!("{block}\n"),
        None => format!("{block}\n{NOTES_TAIL}"),
    };
    if existing.as_deref() == Some(new.as_str()) {
        out.unchanged += 1;
        return Ok(());
    }
    if let Some(p) = path.parent() {
        std::fs::create_dir_all(p)?;
    }
    std::fs::write(path, new)?;
    out.written.push(path.to_path_buf());
    Ok(())
}

/// Precomputed lookups shared by all renders.
pub struct Ctx<'g> {
    g: &'g Graph,
    root: PathBuf,
    /// symbol index → number of incoming resolved references
    refs: HashMap<usize, usize>,
}

impl<'g> Ctx<'g> {
    pub fn new(root: &Path, g: &'g Graph) -> Self {
        let mut refs: HashMap<usize, usize> = HashMap::new();
        for (file, e) in &g.edges {
            // References from tests don't make a symbol "key".
            if g.source_of(file, e).is_some_and(|s| g.syms[s].sym.test) {
                continue;
            }
            // Count only unambiguous references so `.as_str()`-style calls don't inflate counts.
            if let [i] = g.resolve(file, e)[..] {
                if g.syms[i].file != *file {
                    *refs.entry(i).or_default() += 1;
                }
            }
        }
        Ctx { g, root: root.to_path_buf(), refs }
    }

    /// ≈ tokens of all parsed source files (what an agent would read without the map).
    pub fn source_tokens(&self) -> usize {
        self.g
            .files
            .iter()
            .filter(|f| f.parsed)
            .filter_map(|f| std::fs::metadata(self.root.join(&f.path)).ok())
            .map(|m| (m.len() as usize).div_ceil(4))
            .sum()
    }

    fn files_in(&self, dir: &str) -> Vec<usize> {
        (0..self.g.files.len()).filter(|&i| dir_of(&self.g.files[i].path) == dir).collect()
    }

    fn subdirs(&self, dir: &str) -> Vec<String> {
        self.g
            .dirs()
            .into_iter()
            .filter(|d| !d.is_empty() && dir_of(d) == dir)
            .collect()
    }

    /// Best-effort one-line purpose of a directory.
    pub fn dir_purpose(&self, dir: &str) -> Option<String> {
        let join = |name: &str| if dir.is_empty() { name.to_string() } else { format!("{dir}/{name}") };
        for f in ["mod.rs", "lib.rs", "main.rs", "src/lib.rs", "src/main.rs"] {
            let p = join(f);
            if let Some(doc) = self.g.files.iter().find(|x| x.path == p).and_then(|x| x.module_doc.as_deref()) {
                if let Some(s) = gitnext_parse::first_sentence(doc) {
                    return Some(s);
                }
            }
        }
        // Cargo.toml / package.json description
        if let Ok(t) = std::fs::read_to_string(self.root.join(join("Cargo.toml"))) {
            if let Some(d) = toml_description(&t) {
                return Some(d);
            }
        }
        let docs: Vec<&str> = self
            .files_in(dir)
            .into_iter()
            .filter_map(|i| self.g.files[i].module_doc.as_deref())
            .collect();
        if docs.len() == 1 {
            return gitnext_parse::first_sentence(docs[0]);
        }
        if let Some(n) = self.g.dir_notes.get(dir) {
            return Some(format!("≈ {n}"));
        }
        self.dir_heuristic(dir)
    }

    /// No docs, no notes: name the most referenced public types and functions.
    fn dir_heuristic(&self, dir: &str) -> Option<String> {
        let g = self.g;
        let mut types: Vec<(usize, &str)> = Vec::new();
        let mut fns: Vec<(usize, &str)> = Vec::new();
        for (i, r) in g.syms.iter().enumerate() {
            if dir_of(&r.file) != dir || r.sym.test || !r.sym.is_public() || r.sym.trait_impl.is_some() {
                continue;
            }
            let n = self.refs.get(&i).copied().unwrap_or(0);
            if r.sym.kind.is_type() {
                types.push((n, &r.sym.name));
            } else if r.sym.kind == Kind::Function {
                fns.push((n, &r.sym.name));
            }
        }
        if types.is_empty() && fns.is_empty() {
            return None;
        }
        types.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(b.1)));
        fns.sort_by(|a, b| b.0.cmp(&a.0).then(a.1.cmp(b.1)));
        let mut parts = Vec::new();
        if !types.is_empty() {
            parts.push(format!("types {}", types.iter().take(4).map(|x| x.1).collect::<Vec<_>>().join(", ")));
        }
        if !fns.is_empty() {
            parts.push(format!("functions {}", fns.iter().take(4).map(|x| x.1).collect::<Vec<_>>().join(", ")));
        }
        Some(format!("≈ {}", parts.join("; ")))
    }
}

/// Top-level area of a path: `crates/core/src/x.rs` → `crates/core`, `py/pkg/m.py` → `py/pkg`, `main.c` → `/`.
pub fn area(path: &str) -> String {
    let segs: Vec<&str> = path.split('/').collect();
    match segs.len() {
        0 | 1 => "/".into(),
        2 => segs[0].into(),
        _ => format!("{}/{}", segs[0], segs[1]),
    }
}


/// Area-level dependency edges: (from, to, refs).
pub fn area_graph(g: &Graph) -> Vec<(String, String, usize)> {
    let mut m: BTreeMap<(String, String), usize> = BTreeMap::new();
    for (file, e) in &g.edges {
        if e.kind == EdgeKind::Imports {
            continue;
        }
        let from = area(file);
        let mut seen = HashSet::new();
        for t in g.resolve(file, e) {
            let to = area(&g.syms[t].file);
            if to != from && seen.insert(to.clone()) && !g.syms[t].sym.test && g.source_of(file, e).is_some_and(|s| !g.syms[s].sym.test) {
                *m.entry((from.clone(), to)).or_default() += 1;
            }
        }
    }
    m.into_iter().map(|((a, b), n)| (a, b, n)).collect()
}

/// Mermaid `graph LR` of areas (rendered by GitHub / most Markdown viewers).
/// Areas in dependency order: `layers[0]` are foundations (use no other area),
/// each later layer uses only earlier ones. Areas in a dependency cycle share a
/// layer and are listed in `cycles`.
#[derive(Debug, Default, Clone)]
pub struct Layers {
    pub layers: Vec<Vec<String>>,
    pub cycles: Vec<Vec<String>>,
    /// area → areas it uses, with reference counts (strongest first)
    pub uses: BTreeMap<String, Vec<(String, usize)>>,
}

pub fn layers(g: &Graph) -> Layers {
    let edges = area_graph(g);
    let mut nodes: BTreeSet<String> = g.files.iter().filter(|f| f.parsed).map(|f| area(&f.path)).collect();
    let mut uses: BTreeMap<String, Vec<(String, usize)>> = BTreeMap::new();
    for (a, b, n) in &edges {
        if a == b {
            continue;
        }
        nodes.insert(a.clone());
        nodes.insert(b.clone());
        uses.entry(a.clone()).or_default().push((b.clone(), *n));
    }
    for v in uses.values_mut() {
        v.sort_by(|x, y| y.1.cmp(&x.1).then(x.0.cmp(&y.0)));
    }
    // strongly connected components (Tarjan) so cycles don't break the ordering
    let names: Vec<String> = nodes.into_iter().collect();
    let idx: HashMap<&str, usize> = names.iter().enumerate().map(|(i, n)| (n.as_str(), i)).collect();
    let adj: Vec<Vec<usize>> = names.iter().map(|n| uses.get(n).map(|v| v.iter().filter_map(|(t, _)| idx.get(t.as_str()).copied()).collect()).unwrap_or_default()).collect();
    let n = names.len();
    let (mut index, mut low, mut on, mut comp) = (vec![usize::MAX; n], vec![0; n], vec![false; n], vec![usize::MAX; n]);
    let (mut stack, mut next, mut ncomp) = (Vec::new(), 0usize, 0usize);
    #[allow(clippy::too_many_arguments)]
    fn strong(v: usize, adj: &[Vec<usize>], index: &mut [usize], low: &mut [usize], on: &mut [bool], comp: &mut [usize], stack: &mut Vec<usize>, next: &mut usize, ncomp: &mut usize) {
        index[v] = *next;
        low[v] = *next;
        *next += 1;
        stack.push(v);
        on[v] = true;
        for &w in &adj[v] {
            if index[w] == usize::MAX {
                strong(w, adj, index, low, on, comp, stack, next, ncomp);
                low[v] = low[v].min(low[w]);
            } else if on[w] {
                low[v] = low[v].min(index[w]);
            }
        }
        if low[v] == index[v] {
            while let Some(w) = stack.pop() {
                on[w] = false;
                comp[w] = *ncomp;
                if w == v {
                    break;
                }
            }
            *ncomp += 1;
        }
    }
    for v in 0..n {
        if index[v] == usize::MAX {
            strong(v, &adj, &mut index, &mut low, &mut on, &mut comp, &mut stack, &mut next, &mut ncomp);
        }
    }
    // Tarjan emits components in reverse topological order: dependencies first
    let mut level = vec![0usize; ncomp];
    for c in 0..ncomp {
        for v in (0..n).filter(|&v| comp[v] == c) {
            for &w in &adj[v] {
                if comp[w] != c {
                    level[c] = level[c].max(level[comp[w]] + 1);
                }
            }
        }
    }
    let depth = level.iter().copied().max().unwrap_or(0);
    let mut out = Layers { layers: vec![vec![]; if n == 0 { 0 } else { depth + 1 }], uses, ..Default::default() };
    for (c, &lv) in level.iter().enumerate() {
        let members: Vec<String> = (0..n).filter(|&v| comp[v] == c).map(|v| names[v].clone()).collect();
        if members.len() > 1 {
            out.cycles.push(members.clone());
        }
        out.layers[lv].extend(members);
    }
    for l in &mut out.layers {
        l.sort();
    }
    out
}

pub fn mermaid(g: &Graph) -> Option<String> {
    let edges = area_graph(g);
    if edges.is_empty() {
        return None;
    }
    let id = |a: &str| -> String { a.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect::<String>() };
    let mut nodes: BTreeSet<&str> = BTreeSet::new();
    let mut top: Vec<&(String, String, usize)> = edges.iter().collect();
    top.sort_by_key(|e| std::cmp::Reverse(e.2));
    top.truncate(30);
    let mut s = String::from("```mermaid\ngraph LR\n");
    for (a, b, _) in &top {
        nodes.insert(a);
        nodes.insert(b);
    }
    for n in &nodes {
        let _ = writeln!(s, "  {}[\"{}\"]", id(n), n);
    }
    for (a, b, n) in &top {
        let _ = writeln!(s, "  {} -->|{n}| {}", id(a), id(b));
    }
    s.push_str("```\n");
    Some(s)
}


/// 12345 → "12.3k"
pub fn fmt_k(n: usize) -> String {
    if n >= 10_000 {
        format!("{}k", n / 1000)
    } else if n >= 1000 {
        format!("{:.1}k", n as f64 / 1000.0)
    } else {
        n.to_string()
    }
}

fn toml_description(t: &str) -> Option<String> {
    t.lines()
        .find(|l| l.trim_start().starts_with("description"))
        .and_then(|l| l.split_once('='))
        .map(|(_, v)| v.trim().trim_matches('"').to_string())
        .filter(|s| !s.is_empty())
}

fn short(sig: &str) -> String {
    if sig.chars().count() > MAX_SIG {
        sig.chars().take(MAX_SIG - 1).collect::<String>() + "…"
    } else {
        sig.to_string()
    }
}

fn file_name(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

/// Render the auto section of a directory's DIR.md.
/// How much API detail a DIR.md carries; chosen to fit the token budget.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Detail {
    /// every public signature with docs
    Full,
    /// types + functions with signatures; methods as names
    Compact,
    /// the most referenced symbols per file, rest via `gitnext outline`
    Brief,
}

/// Token budget for one DIR.md (override with GITNEXT_MAP_BUDGET).
fn budget() -> usize {
    std::env::var("GITNEXT_MAP_BUDGET").ok().and_then(|v| v.parse().ok()).unwrap_or(1200)
}

/// Directory map, as detailed as fits the budget.
pub fn render_dir(ctx: &Ctx, dir: &str) -> String {
    let b = budget();
    for level in [Detail::Full, Detail::Compact] {
        let s = render_dir_at(ctx, dir, level);
        if est_tokens(&s) <= b {
            return s;
        }
    }
    render_dir_at(ctx, dir, Detail::Brief)
}

pub fn render_dir_at(ctx: &Ctx, dir: &str, level: Detail) -> String {
    let g = ctx.g;
    let mut s = String::new();
    let title = if dir.is_empty() { "/ (repository root)".to_string() } else { format!("{dir}/") };
    let _ = writeln!(s, "# `{title}`\n");
    match ctx.dir_purpose(dir) {
        Some(p) => {
            let _ = writeln!(s, "> {p}\n");
        }
        None => {
            let _ = writeln!(s, "> _Purpose not documented. Add a `//!` module doc or describe it in Notes below._\n");
        }
    }

    let files = ctx.files_in(dir);
    let file_paths: Vec<&str> = files.iter().map(|&i| g.files[i].path.as_str()).collect();
    let syms_here: Vec<usize> = (0..g.syms.len()).filter(|&i| file_paths.contains(&g.syms[i].file.as_str())).collect();
    let lines: u32 = files.iter().map(|&i| g.files[i].lines).sum();
    let is_def = |i: usize| !(g.syms[i].sym.kind == Kind::Module && g.syms[i].sym.start_line == 1);
    let n_defs = syms_here.iter().filter(|&&i| is_def(i) && !g.syms[i].sym.test).count();
    let n_tests = syms_here.iter().filter(|&&i| is_def(i) && g.syms[i].sym.test && g.syms[i].sym.kind.is_callable()).count();
    let tests_note = if n_tests > 0 { format!(" · {n_tests} tests") } else { String::new() };
    let _ = writeln!(s, "**{} files · {} lines · {} symbols{tests_note}**\n", files.len(), lines, n_defs);

    let subs = ctx.subdirs(dir);
    if !subs.is_empty() {
        let _ = writeln!(s, "## Subdirectories\n");
        for d in &subs {
            let name = file_name(d);
            let purpose = ctx.dir_purpose(d).map(|p| format!(" — {p}")).unwrap_or_default();
            let _ = writeln!(s, "- [`{name}/`]({name}/DIR.md){purpose}");
        }
        s.push('\n');
    }

    if !files.is_empty() {
        let _ = writeln!(s, "## Files\n\n| File | Lines | Purpose |\n|---|---:|---|");
        for &i in &files {
            let f = &g.files[i];
            let purpose = f
                .module_doc
                .as_deref()
                .and_then(gitnext_parse::first_sentence)
                .unwrap_or_else(|| if f.parsed { String::new() } else { f.file_type.clone() });
            let _ = writeln!(s, "| `{}` | {} | {} |", file_name(&f.path), f.lines, purpose.replace('|', "\\|"));
        }
        s.push('\n');
    }

    // API, per parsed file
    let parsed: Vec<&str> = files.iter().filter(|&&i| g.files[i].parsed).map(|&i| g.files[i].path.as_str()).collect();
    if !parsed.is_empty() && n_defs > 0 {
        let note = match level {
            Detail::Full => "",
            Detail::Compact => " (compact: methods by name; `gitnext outline <file>` for signatures)",
            Detail::Brief => " (most referenced only; `gitnext outline <file>` for everything)",
        };
        let _ = writeln!(s, "## API{note}\n");
        for path in parsed {
            render_file_api(ctx, path, &mut s, level);
        }
    }

    // Implementations declared here
    let mut impls = BTreeMap::<String, Vec<String>>::new();
    for (file, e) in &g.edges {
        if file_paths.contains(&file.as_str()) && e.kind == gitnext_parse::EdgeKind::Implements {
            impls.entry(gitnext_parse::last_segment(&e.from).to_string()).or_default().push(e.to.clone());
        }
    }
    if !impls.is_empty() && level == Detail::Full {
        let _ = writeln!(s, "## Implementations\n");
        for (ty, traits) in impls {
            let t: Vec<String> = traits.iter().map(|t| format!("`{t}`")).collect();
            let _ = writeln!(s, "- `{ty}` implements {}", t.join(", "));
        }
        s.push('\n');
    }

    let deps = g.dir_deps(dir);
    if !deps.depends_on.is_empty() || !deps.used_by.is_empty() {
        let _ = writeln!(s, "## Dependencies\n");
        let fmt = |v: &[(String, usize)]| {
            v.iter()
                .take(10)
                .map(|(d, n)| format!("`{}` ({n})", if d.is_empty() { "/" } else { d }))
                .collect::<Vec<_>>()
                .join(", ")
        };
        if !deps.depends_on.is_empty() {
            let _ = writeln!(s, "- **Depends on:** {}", fmt(&deps.depends_on));
        }
        if !deps.used_by.is_empty() {
            let _ = writeln!(s, "- **Used by:** {}", fmt(&deps.used_by));
        }
        s.push('\n');
    }
    s
}

fn render_agents_compact(ctx: &Ctx, mut s: String) -> String {
    let g = ctx.g;
    let _ = writeln!(s, "Indexed by gitnext: use the code tools (outline → read → replace_symbol) instead of reading whole files.\n");
    let _ = writeln!(s, "Areas, foundations first (each uses only the ones above it):");
    let ly = layers(g);
    for a in ly.layers.iter().flatten() {
        let dir = if a == "/" { String::new() } else { a.clone() };
        let n = g.files.iter().filter(|f| f.parsed && area(&f.path) == *a).count();
        let purpose = ctx.dir_purpose(&dir).map(|p| format!(" — {p}")).unwrap_or_default();
        let uses = ly.uses.get(a).map(|v| format!(" · uses {}", v.iter().take(3).map(|(t, _)| t.as_str()).collect::<Vec<_>>().join(", "))).unwrap_or_default();
        let _ = writeln!(s, "- {a} ({n} files){purpose}{uses}");
    }
    for c in &ly.cycles {
        let _ = writeln!(s, "- cycle: {} use each other", c.join(" and "));
    }
    let mut top: Vec<(usize, usize)> = ctx.refs.iter().filter(|(i, _)| g.syms[**i].sym.kind != Kind::Module && !g.syms[**i].sym.test).map(|(i, n)| (*n, *i)).collect();
    top.sort_by(|a, b| b.0.cmp(&a.0).then(g.syms[a.1].sym.qualified.cmp(&g.syms[b.1].sym.qualified)));
    if !top.is_empty() {
        let _ = writeln!(s, "\nKey symbols:");
        for (_, i) in top.into_iter().take(8) {
            let r = &g.syms[i];
            let _ = writeln!(s, "- {} ({}) in {}", r.sym.name, r.sym.kind.as_str(), r.file);
        }
    }
    s
}

fn render_file_api(ctx: &Ctx, path: &str, s: &mut String, level: Detail) {
    let g = ctx.g;
    if level == Detail::Brief {
        return render_file_brief(ctx, path, s);
    }
    let compact = level == Detail::Compact;
    // Test code is summarised, not listed: agents rarely need it to understand an API.
    let ids: Vec<usize> = g.in_file(path).into_iter().filter(|&i| !g.syms[i].sym.test).collect();
    let is_file_mod = |i: usize| g.syms[i].sym.kind == Kind::Module && g.syms[i].sym.start_line == 1;
    let top: Vec<usize> = ids.iter().copied().filter(|&i| !is_file_mod(i) && g.syms[i].sym.kind != Kind::Method).collect();
    let methods: Vec<usize> = ids.iter().copied().filter(|&i| g.syms[i].sym.kind == Kind::Method).collect();
    if top.is_empty() && methods.is_empty() {
        return;
    }
    let _ = writeln!(s, "### `{}`\n", file_name(path));

    let mut internal = Vec::new();
    let mut used_methods = std::collections::HashSet::new();
    for &i in &top {
        let sym = &g.syms[i].sym;
        let own: Vec<usize> = methods
            .iter()
            .copied()
            .filter(|&m| g.syms[m].sym.parent.as_deref() == Some(sym.qualified.as_str()))
            .collect();
        if !sym.is_public() && own.is_empty() {
            internal.push(format!("{} `{}`", sym.kind.as_str(), sym.name));
            continue;
        }
        line_for(ctx, i, 0, s);
        if compact {
            if matches!(sym.kind, Kind::Struct | Kind::Union | Kind::Class | Kind::Enum) && !sym.params.is_empty() {
                let f: Vec<&str> = sym.params.iter().take(16).map(|p| p.name.as_str()).collect();
                let label = if sym.kind == Kind::Enum { "variants" } else { "fields" };
                let _ = writeln!(s, "  - {label}: {}{}", f.join(", "), if sym.params.len() > 16 { ", …" } else { "" });
            }
            let names: Vec<&str> = own.iter().filter(|&&m| g.syms[m].sym.is_public() && g.syms[m].sym.trait_impl.is_none()).map(|&m| g.syms[m].sym.name.as_str()).collect();
            let mut traits: Vec<&str> = own.iter().filter_map(|&m| g.syms[m].sym.trait_impl.as_deref()).collect();
            traits.sort_unstable();
            traits.dedup();
            if !names.is_empty() {
                let _ = writeln!(s, "  - methods: {}", names.join(", "));
            }
            if !traits.is_empty() {
                let _ = writeln!(s, "  - implements: {}", traits.join(", "));
            }
            used_methods.extend(own);
            continue;
        }
        if matches!(sym.kind, Kind::Struct | Kind::Union) && !sym.params.is_empty() {
            let f: Vec<String> = sym
                .params
                .iter()
                .take(12)
                .map(|p| format!("`{}: {}`", p.name, p.ty))
                .collect();
            let _ = writeln!(s, "  - fields: {}{}", f.join(", "), if sym.params.len() > 12 { ", …" } else { "" });
        }
        if sym.kind == Kind::Enum && !sym.params.is_empty() {
            let v: Vec<String> = sym.params.iter().take(16).map(|p| format!("`{}`", p.name)).collect();
            let _ = writeln!(s, "  - variants: {}{}", v.join(", "), if sym.params.len() > 16 { ", …" } else { "" });
        }
        render_methods(ctx, &own, s);
        used_methods.extend(own);
    }
    // impl blocks for types defined elsewhere
    let mut by_owner: BTreeMap<String, Vec<usize>> = BTreeMap::new();
    for &m in &methods {
        if !used_methods.contains(&m) {
            by_owner.entry(g.syms[m].sym.parent.clone().unwrap_or_default()).or_default().push(m);
        }
    }
    let rust = path.ends_with(".rs");
    for (owner, ms) in by_owner {
        let o = gitnext_parse::last_segment(&owner);
        if compact {
            let names: Vec<&str> = ms.iter().filter(|&&m| g.syms[m].sym.is_public()).map(|&m| g.syms[m].sym.name.as_str()).collect();
            if !names.is_empty() {
                let _ = writeln!(s, "- `{o}` methods: {}", names.join(", "));
            }
            continue;
        }
        if rust {
            let _ = writeln!(s, "- impl `{o}`");
        } else {
            let _ = writeln!(s, "- methods of `{o}`");
        }
        render_methods(ctx, &ms, s);
    }
    if !internal.is_empty() {
        if compact {
            let _ = writeln!(s, "- _internal:_ {} items", internal.len());
        } else {
            let _ = writeln!(s, "- _internal:_ {}", internal.join(", "));
        }
    }
    s.push('\n');
}

/// Most referenced public symbols of a file (types and functions), the rest counted.
fn render_file_brief(ctx: &Ctx, path: &str, s: &mut String) {
    let g = ctx.g;
    let mut ids: Vec<usize> = g
        .in_file(path)
        .into_iter()
        .filter(|&i| {
            let x = &g.syms[i].sym;
            !x.test && x.is_public() && x.trait_impl.is_none() && !(x.kind == Kind::Module && x.start_line == 1) && (x.kind.is_type() || x.kind == Kind::Function || x.kind == Kind::Method)
        })
        .collect();
    if ids.is_empty() {
        return;
    }
    let total = ids.len();
    ids.sort_by_key(|&i| (std::cmp::Reverse(ctx.refs.get(&i).copied().unwrap_or(0)), !g.syms[i].sym.kind.is_type(), g.syms[i].sym.start_line));
    ids.truncate(6);
    ids.sort_by_key(|&i| g.syms[i].sym.start_line);
    let _ = writeln!(s, "### `{}`\n", file_name(path));
    for i in ids {
        let x = &g.syms[i].sym;
        match x.parent.as_deref().filter(|_| x.kind == Kind::Method) {
            Some(owner) if !x.signature.contains(&format!("::{}", x.name)) => {
                // show whose method it is: `fn LineStep::new(…)`
                let o = gitnext_parse::last_segment(owner);
                let sig = x.signature.replacen(&format!("{}(", x.name), &format!("{o}::{}(", x.name), 1);
                let mut line = format!("- `{}`", short(&sig));
                if let Some(sum) = &x.summary {
                    let _ = write!(line, " — {}{sum}", if x.inferred { "≈ " } else { "" });
                }
                let _ = writeln!(s, "{line}");
            }
            _ => line_for(ctx, i, 0, s),
        }
    }
    if total > 6 {
        let _ = writeln!(s, "- … +{} more", total - 6);
    }
    s.push('\n');
}

fn render_methods(ctx: &Ctx, ms: &[usize], s: &mut String) {
    let g = ctx.g;
    let mut private = Vec::new();
    for &m in ms {
        let sym = &g.syms[m].sym;
        if sym.is_public() {
            line_for(ctx, m, 1, s);
        } else {
            private.push(format!("`{}`", sym.name));
        }
    }
    if !private.is_empty() {
        let _ = writeln!(s, "  - _private:_ {}", private.join(", "));
    }
}

fn line_for(ctx: &Ctx, i: usize, depth: usize, s: &mut String) {
    let sym = &ctx.g.syms[i].sym;
    let indent = "  ".repeat(depth);
    let mut line = format!("{indent}- `{}`", short(&sym.signature));
    if let Some(t) = &sym.trait_impl {
        let _ = write!(line, " _(impl {t})_");
    }
    if let Some(sum) = &sym.summary {
        let mark = if sym.inferred { "≈ " } else { "" };
        let _ = write!(line, " — {mark}{sum}");
    }
    if let Some(n) = ctx.refs.get(&i).filter(|n| **n > 1) {
        let _ = write!(line, " · {n} refs");
    }
    let _ = writeln!(s, "{line}");
}

/// Settings in `.gitnext/config` (`key = value` lines, `#` comments).
pub fn config_value(root: &Path, key: &str) -> Option<String> {
    let text = std::fs::read_to_string(root.join(GITNEXT_DIR).join("config")).ok()?;
    text.lines().filter(|l| !l.trim_start().starts_with('#')).find_map(|l| {
        let (k, v) = l.split_once('=')?;
        (k.trim() == key).then(|| v.trim().to_string())
    })
}

/// Set one `key = value` in `.gitnext/config`, keeping the rest.
pub fn set_config_value(root: &Path, key: &str, value: &str) -> Result<bool> {
    let p = root.join(GITNEXT_DIR).join("config");
    let old = std::fs::read_to_string(&p).unwrap_or_default();
    let mut found = false;
    let mut lines: Vec<String> = old
        .lines()
        .map(|l| match l.split_once('=') {
            Some((k, _)) if k.trim() == key && !l.trim_start().starts_with('#') => {
                found = true;
                format!("{key} = {value}")
            }
            _ => l.to_string(),
        })
        .collect();
    if !found {
        if lines.is_empty() {
            lines.push("# gitnext settings (committed with the repo)".into());
        }
        lines.push(format!("{key} = {value}"));
    }
    let new = lines.join("\n") + "\n";
    if new == old {
        return Ok(false);
    }
    std::fs::create_dir_all(p.parent().unwrap())?;
    std::fs::write(&p, new)?;
    Ok(true)
}

/// Root AGENTS.md block: how to navigate this repo with gitnext.
///
/// `agents_md = compact` in `.gitnext/config` (set by `gitnext setup loca`)
/// keeps it short: small local models read AGENTS.md into a 16k context, and
/// their tool instructions live in LOCA.md.
pub fn render_agents(ctx: &Ctx) -> String {
    let g = ctx.g;
    let name = ctx.root.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
    let compact = config_value(&ctx.root, "agents_md").as_deref() == Some("compact");
    let mut s = String::new();
    let _ = writeln!(s, "# Agent guide: `{name}`\n");
    if compact {
        return render_agents_compact(ctx, s);
    }
    let _ = writeln!(
        s,
        "This repository is indexed by **gitnext**. Don't read or rewrite whole files: \
         navigate with the map and the code graph, read only the symbols you need, edit by symbol.\n\n\
         **Workflow (cheapest first):**\n\n\
         1. `gitnext overview`: languages, areas, entry points, dependencies, activity (once per session).\n\
         2. `gitnext map <dir>` → `gitnext outline <file|dir>`: purpose and signatures, no bodies.\n\
         3. `gitnext read <Sym> [<Sym>…]`: exact source of just those symbols (`Name@LINE` picks an overload).\n\
         4. Edit without reading the file: `gitnext edit replace <Sym>` (new code on stdin), `edit insert-after`, \
         `edit delete`, `gitnext rename <Sym> <new>` (all references). Edits that don't parse are rejected.\n\
         5. Before changing a signature: `gitnext impact <Sym>`; then `gitnext tests-for <Sym>` gives the exact test command.\n\
         6. Errors / panics / tracebacks: `gitnext locate` (paste on stdin) → the functions at those lines.\n\n\
         **More:** `show <Sym>` · `search <text>` · `callers`/`callees` · `hierarchy <Type>` · `deps <dir>` · \
         `history <Sym>` · `changelog a..b` · `since <rev>` · `diff` · `context \"<task>\"` · `hotspots` · `dead` · `entrypoints`.\n\n\
         Symbols: `Name`, `Type::method`, `Type.method` or fully qualified. Output is compact text; `--json` for structure. \
         Summaries marked `≈` are inferred (LLM / agent), not written by the authors. \
         With MCP (`gitnext mcp`) all of this are tools; after understanding undocumented code, call `annotate` so the next session gets it for free.\n\n\
         `gitnext commit` refreshes this map and appends a symbol-level change list to the commit message.\n"
    );

    let parsed = g.files.iter().filter(|f| f.parsed).count();
    let mut langs: BTreeMap<&str, usize> = BTreeMap::new();
    for f in g.files.iter().filter(|f| f.parsed) {
        *langs.entry(f.file_type.as_str()).or_default() += 1;
    }
    let langs: Vec<String> = langs.iter().map(|(l, n)| format!("{l} ({n})")).collect();
    let n_syms = g.syms.iter().filter(|s| !(s.sym.kind == Kind::Module && s.sym.start_line == 1) && !s.sym.test).count();
    let src_tok = ctx.source_tokens();
    let _ = (parsed, &langs, n_syms);
    let _ = writeln!(s, "## Overview\n\n{}. Reading all of it ≈ {} tokens.\n", g.counts().line(), fmt_k(src_tok));
    if let Some(p) = ctx.dir_purpose("") {
        let _ = writeln!(s, "> {p}\n");
    }

    let _ = writeln!(s, "## Layout\n\n| Directory | Files | Purpose |\n|---|---:|---|");
    let root_code: Vec<&str> = g.files.iter().filter(|f| f.parsed && !f.path.contains('/')).map(|f| f.path.as_str()).collect();
    if !root_code.is_empty() {
        let purpose = ctx.dir_purpose("").unwrap_or_default().replace('|', "\\|");
        let names = root_code.iter().take(4).map(|f| format!("`{f}`")).collect::<Vec<_>>().join(", ");
        let _ = writeln!(s, "| [`./`](.gitnext/map/DIR.md) (root: {names}) | {} | {purpose} |", g.files.iter().filter(|f| !f.path.contains('/')).count());
    }
    for d in g.dirs().into_iter().filter(|d| !d.is_empty() && d.matches('/').count() <= 2) {
        let n = g.files.iter().filter(|f| f.path.starts_with(&format!("{d}/"))).count();
        let purpose = ctx.dir_purpose(&d).unwrap_or_default().replace('|', "\\|");
        let _ = writeln!(s, "| [`{d}/`](.gitnext/map/{d}/DIR.md) | {n} | {purpose} |");
    }
    s.push('\n');

    if let Some(m) = mermaid(g) {
        let _ = writeln!(s, "## Architecture (area → area, number of references)\n\n{m}");
    }

    let mut top: Vec<(usize, usize)> = ctx
        .refs
        .iter()
        .filter(|(i, _)| g.syms[**i].sym.kind != Kind::Module && !g.syms[**i].sym.test)
        .map(|(i, n)| (*n, *i))
        .collect();
    top.sort_by(|a, b| b.0.cmp(&a.0).then(g.syms[a.1].sym.qualified.cmp(&g.syms[b.1].sym.qualified)));
    if !top.is_empty() {
        let _ = writeln!(s, "## Key symbols (most referenced across files)\n");
        for (n, i) in top.into_iter().take(15) {
            let r = &g.syms[i];
            let sum = r.sym.summary.as_deref().map(|x| format!(" — {x}")).unwrap_or_default();
            let _ = writeln!(s, "- `{}` {} in `{}`{sum} · {n} refs", r.sym.name, r.sym.kind.as_str(), r.file);
        }
        s.push('\n');
    }
    s
}
